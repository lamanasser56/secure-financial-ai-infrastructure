"""Idempotent platform bootstrap job (`python -m agent_platform.programs.bootstrap all`).

database: non-owner login roles (NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS), databases, the
          LiteLLM schema, the RLS tenant schema (FORCE ROW LEVEL SECURITY) and synthetic fixtures.
finance:  trusted frontdoor/read-broker roles, disabled legacy worker roles, FORCE RLS on expenses, and the
          local users (argon2id hashes only; the plaintext passwords exist only in the owner's private state).
keys:     scoped gateway virtual keys (pre-generated by `make secrets`) with model = the stable alias only and a
          30-day budget; the sum of all key budgets is the owner-approved $10/month.
Re-running reconciles declared roles/grants and private gateway keys; legacy agent sessions are terminated during the reviewed cutover. Never prints secret values.
"""
import hashlib
import json
from pathlib import Path
import sys
import time
import urllib.error
import urllib.request

TENANTS = {'fixture-a': '7d5bba9e-0f6f-4f3e-9b6c-2b8f2f0a1a01', 'fixture-b': 'c4a1f3de-5b2e-4d8f-8a7c-91e0b6d2c302'}
SQL = Path('/sql')
GATEWAY = 'http://gateway-provider.platform.svc.cluster.local:4001'


def log(**fields):
    print(json.dumps({'audit_event': 'bootstrap', 'component': 'bootstrap', **fields}, sort_keys=True), flush=True)


def url(config, role, database):
    password = {'postgres': config['owner_password'], 'portfolio_gateway': config['gateway_password']}[role]
    return 'postgresql://' + role + ':' + password + '@' + config['host'] + '/' + database


def database(config):
    import psycopg
    from psycopg import sql
    with psycopg.connect(url(config, 'postgres', 'postgres'), connect_timeout=5, autocommit=True) as db:
        for role, password in (('portfolio_gateway', config['gateway_password']), ('portfolio_app', config['app_password'])):
            exists = db.execute('SELECT 1 FROM pg_roles WHERE rolname=%s', (role,)).fetchone()
            verb = 'ALTER' if exists else 'CREATE'
            db.execute(sql.SQL(verb + ' ROLE {} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS PASSWORD {}')
                       .format(sql.Identifier(role), sql.Literal(password)))
        for name, owner in (('litellm', 'portfolio_gateway'), ('portfolio_demo', None)):
            if not db.execute('SELECT 1 FROM pg_database WHERE datname=%s', (name,)).fetchone():
                db.execute(sql.SQL('CREATE DATABASE {}' + (' OWNER {}' if owner else '')).format(
                    sql.Identifier(name), *([sql.Identifier(owner)] if owner else [])))
            db.execute(sql.SQL('REVOKE CONNECT ON DATABASE {} FROM PUBLIC').format(sql.Identifier(name)))
        db.execute('GRANT CONNECT ON DATABASE litellm TO portfolio_gateway')
        db.execute('GRANT CONNECT ON DATABASE portfolio_demo TO portfolio_app')
    with psycopg.connect(url(config, 'portfolio_gateway', 'litellm'), connect_timeout=5, autocommit=True) as db:
        if not db.execute("SELECT to_regclass('public.\"LiteLLM_VerificationToken\"')").fetchone()[0]:
            db.execute((SQL / 'litellm-schema.sql').read_text())
            log(step='litellm_schema', created=True)
        if config.get('boundary_contract') != 2:
            raise SystemExit('bootstrap:boundary_migration_required')
        keep = [hashlib.sha256(k['key'].encode()).hexdigest() for k in config['virtual_keys']]
        db.execute('DELETE FROM public."LiteLLM_VerificationToken" WHERE NOT (token = ANY(%s))', (keep,))

    with psycopg.connect(url(config, 'postgres', 'portfolio_demo'), connect_timeout=5, autocommit=True) as db:
        if not db.execute("SELECT to_regclass('portfolio_demo.expenses')").fetchone()[0]:
            db.execute((SQL / 'tenant.sql').read_text())
            fixtures = json.loads((SQL / 'expenses.json').read_text())
            for tenant, rows in fixtures['tenants'].items():
                for row in rows:
                    db.execute('INSERT INTO portfolio_demo.expenses(tenant_id,period,category,amount_minor_units) VALUES(%s,%s,%s,%s)',
                               (TENANTS[tenant], row['period'], row['category'], row['amount_minor_units']))
            log(step='tenant_schema', created=True)
        rls = db.execute("SELECT relrowsecurity, relforcerowsecurity FROM pg_class WHERE oid='portfolio_demo.expenses'::regclass").fetchone()
        bypass = db.execute("SELECT rolbypassrls, rolsuper FROM pg_roles WHERE rolname='portfolio_app'").fetchone()
        if rls != (True, True) or bypass != (False, False):
            raise SystemExit('bootstrap:rls_contract_violated')
    log(step='database', rls_forced=True, app_role_bypassrls=False)


FINANCE_ROLES = ('finance_web', 'finance_agent')
FINANCE_CATEGORIES = ('food', 'transport', 'shopping', 'bills', 'subscriptions', 'health', 'travel', 'other')
CATEGORY_CONSTRAINT = ('ALTER TABLE finance.expenses DROP CONSTRAINT IF EXISTS expenses_category_check, '
                       'ADD CONSTRAINT expenses_category_check CHECK (category IN ('
                       + ', '.join(f"'{c}'" for c in FINANCE_CATEGORIES) + '))')
# Owner of the SECURITY DEFINER sign-in lookup: cannot log in, reads finance.users only (idempotent; also for existing DBs).
LOOKUP_OWNERSHIP = (
    'GRANT USAGE ON SCHEMA finance TO finance_owner',
    'GRANT SELECT ON finance.users TO finance_owner',
    'ALTER FUNCTION finance.login_lookup(text) OWNER TO finance_owner',
    'ALTER FUNCTION finance.login_lookup(text) SET search_path = pg_catalog, finance',
    'REVOKE ALL ON FUNCTION finance.login_lookup(text) FROM PUBLIC',
    'GRANT EXECUTE ON FUNCTION finance.login_lookup(text) TO finance_web',
)


def finance(config, connect=None):
    """Idempotent: roles, database `finance`, schema, users; then verify the RLS contract (fail closed)."""
    import psycopg
    from psycopg import sql
    connect = connect or (lambda database: psycopg.connect(url(config, 'postgres', database), connect_timeout=5, autocommit=True))
    secrets = config['finance']
    with connect('postgres') as db:
        for role in FINANCE_ROLES:
            verb = 'ALTER' if db.execute('SELECT 1 FROM pg_roles WHERE rolname=%s', (role,)).fetchone() else 'CREATE'
            db.execute(sql.SQL(verb + ' ROLE {} NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS PASSWORD NULL')
                       .format(sql.Identifier(role)))
        for role, field in (('finance_frontdoor', 'broker_web_password'), ('finance_data_broker', 'broker_read_password')):
            verb = 'ALTER' if db.execute('SELECT 1 FROM pg_roles WHERE rolname=%s', (role,)).fetchone() else 'CREATE'
            db.execute(sql.SQL(verb + ' ROLE {} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS CONNECTION LIMIT 8 PASSWORD {}')
                       .format(sql.Identifier(role), sql.Literal(secrets[field])))
        if not db.execute("SELECT 1 FROM pg_roles WHERE rolname='finance_owner'").fetchone():
            db.execute('CREATE ROLE finance_owner NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS')
        if not db.execute("SELECT 1 FROM pg_database WHERE datname='finance'").fetchone():
            db.execute('CREATE DATABASE finance')
        db.execute('REVOKE CONNECT ON DATABASE finance FROM PUBLIC')
        db.execute('GRANT CONNECT ON DATABASE finance TO finance_web, finance_agent')
    with connect('finance') as db:
        if not db.execute("SELECT to_regclass('finance.expenses')").fetchone()[0]:
            db.execute((SQL / 'finance.sql').read_text())
            log(step='finance_schema', created=True)
        # The legacy roles are NOLOGIN throughout migration. Their grants are revoked below.
        # Category list (keep equal to finance_agent.store.CATEGORIES): re-applied so an existing database gains new
        # categories. A CHECK constraint only; no role, grant or RLS change.
        db.execute(CATEGORY_CONSTRAINT)
        for statement in LOOKUP_OWNERSHIP:
            db.execute(statement)
        for user in secrets['users']:
            existing = db.execute('SELECT id::text FROM finance.users WHERE username = %s', (user['username'],)).fetchone()
            if existing:
                if existing[0] != user['id']:
                    raise SystemExit('bootstrap:reviewed_existing_user_directory_required')
                # Existing IDs/password hashes are preserved; fresh worker routes must match them.
            elif secrets.get('preserve_existing_users'):
                raise SystemExit('bootstrap:existing_user_directory_mismatch')
            else:
                db.execute('INSERT INTO finance.users(id, username, display_name, password_hash) VALUES (%s, %s, %s, %s)',
                           (user['id'], user['username'], user['display_name'], user['password_hash']))
        rls = db.execute("SELECT relrowsecurity, relforcerowsecurity FROM pg_class WHERE oid='finance.expenses'::regclass").fetchone()
        db.execute((SQL / 'finance-boundary.sql').read_text())
        role_state = db.execute("SELECT rolname, rolcanlogin, rolsuper, rolbypassrls FROM pg_roles WHERE rolname IN "
                                "('finance_agent','finance_web','finance_frontdoor','finance_data_broker') ORDER BY rolname").fetchall()
        expected = [('finance_agent', False, False, False), ('finance_data_broker', True, False, False),
                    ('finance_frontdoor', True, False, False), ('finance_web', False, False, False)]
        if (rls != (True, True) or role_state != expected
                or db.execute("SELECT has_table_privilege('finance_data_broker','finance.expenses','INSERT,UPDATE,DELETE')").fetchone()[0]
                or db.execute("SELECT has_table_privilege('finance_data_broker','finance.users','SELECT')").fetchone()[0]
                or db.execute("SELECT has_function_privilege('finance_data_broker','finance.login_lookup(text)','EXECUTE')").fetchone()[0]):
            raise SystemExit('bootstrap:finance_boundary_contract_violated')
    log(step='finance', rls_forced=True, users=len(secrets['users']), agent_read_only=True, lookup_owner='finance_owner')


def _gateway(path, body, master_key, method='POST'):
    request = urllib.request.Request(GATEWAY + path, method=method, data=None if body is None else json.dumps(body).encode(),
                                     headers={'Authorization': 'Bearer ' + master_key, 'Content-Type': 'application/json'})
    with urllib.request.build_opener(urllib.request.ProxyHandler({})).open(request, timeout=10) as response:
        return json.loads(response.read(1 << 20))


def keys(config, wait_seconds=300):
    deadline = time.time() + wait_seconds
    while True:
        try:
            with urllib.request.build_opener(urllib.request.ProxyHandler({})).open(GATEWAY + '/health/liveliness', timeout=5):
                break
        except Exception:
            if time.time() >= deadline:
                raise SystemExit('bootstrap:gateway_not_ready')
            time.sleep(5)
    if round(sum(k['max_budget'] for k in config['virtual_keys']), 2) > 10.0:  # a ceiling: unallocated budget is allowed
        raise SystemExit('bootstrap:budget_total_exceeds_10')
    if config.get('boundary_contract') != 2:
        raise SystemExit('bootstrap:boundary_migration_required')
    for item in config['virtual_keys']:
        try:
            info = _gateway('/key/info?key=' + item['key'], None, config['master_key'], method='GET')
            current = ((info or {}).get('info') or {}).get('max_budget')
            if current != item['max_budget']:  # a manifest changed this key's budget (agent onboarding)
                _gateway('/key/update', {'key': item['key'], 'max_budget': item['max_budget']}, config['master_key'])
            log(step='virtual_key', alias=item['alias'], created=False, max_budget=item['max_budget'])
            continue
        except urllib.error.HTTPError as error:
            if error.code not in (400, 404):
                raise
        _gateway('/key/generate', {'key': item['key'], 'key_alias': item['alias'], 'models': ['secure-financial-chat'],
                                   'max_budget': item['max_budget'], 'budget_duration': '30d',
                                   'rpm_limit': 20, 'max_parallel_requests': 2}, config['master_key'])
        log(step='virtual_key', alias=item['alias'], created=True, max_budget=item['max_budget'])


def main(argv):
    if argv not in (['database'], ['keys'], ['all']):
        raise SystemExit('usage: bootstrap database|keys|all')
    config = json.loads(Path('/secrets/bootstrap/bootstrap.json').read_text())
    if argv[0] in ('database', 'all'):
        database(config)
        if 'finance' in config:
            finance(config)
    if argv[0] in ('keys', 'all'):
        keys(config)


if __name__ == '__main__':
    main(sys.argv[1:])
