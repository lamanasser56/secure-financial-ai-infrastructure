#!/usr/bin/env python3
"""Run every declared workload of the seven release images together and require each one to actually run.

Each container starts from its image with the exact command, args, env, volumes and security context of the rendered
manifests (Deployments, StatefulSets, Jobs; replicas 0 included), on one Docker network whose aliases are the
in-cluster Service names. Secrets are synthetic, generated by the platform's own generator; nothing is real and no
cloud credential exists. Pass: the Job completes, and every long-running container passes its readiness/startup
probe and then keeps passing it with no restart for the stability window. Image import sweeps run alongside but
never replace this.
"""
import argparse
import base64
import datetime
import json
import os
from pathlib import Path
import secrets
import shutil
import socket
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'platform/core/src'), str(ROOT / 'platform/clouds/gke'), str(ROOT)]

PROJECT = 'smoke-fixture'
LOCK_KEYS = {'gateway': 'agent-platform-gateway', 'database': 'agent-platform-database',
             'redactor': 'agent-platform-redactor', 'app': 'agent-platform-app', 'ops-agent': 'agent-platform-ops',
             'agent-financial': 'agent-financial', 'platform-guide': 'platform-guide'}
READY_SECONDS, JOB_SECONDS, STABLE_SECONDS, PERIOD = 600, 720, 60, 5


def docker(*args, check=True, capture=True):
    result = subprocess.run(['docker', *args], capture_output=capture, text=True)
    if check and result.returncode:
        raise RuntimeError('docker ' + args[0] + ' failed: ' + (result.stderr or '')[-500:])
    return result


def render_workloads(kubectl):
    """Rendered manifests with a fixture lock whose placeholder digests map back to the seven logical images."""
    import render
    import yaml
    digests = {key: format(i + 1, 'x') * 64 for i, key in enumerate(LOCK_KEYS)}
    lock = {'schema_version': 2, 'source_commit': '0' * 40, 'runtime_contract': 'trusted-boundaries-v2',
            'registry': 'us-east1-docker.pkg.dev/' + PROJECT + '/sdp-evaluation-images/',
            'images': {key: name + '@sha256:' + digests[key] for key, name in LOCK_KEYS.items()}}
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / 'lock.json'
        path.write_text(json.dumps(lock))
        from types import SimpleNamespace
        raw, _ = render.render(SimpleNamespace(
            images_lock=path, project_id=PROJECT, control_plane_cidr='172.16.0.16/28',
            gateway_gsa='smoke-gateway@' + PROJECT + '.iam.gserviceaccount.com',
            redactor_gsa='smoke-redactor@' + PROJECT + '.iam.gserviceaccount.com', kubectl=kubectl))
    docs = [d for d in yaml.safe_load_all(raw) if d]
    by_digest = {digests[key]: name for key, name in LOCK_KEYS.items()}
    return docs, by_digest


def synthetic_secrets():
    """The platform's own generator with a throwaway passphrase: real shapes, synthetic values."""
    from agent_platform.platform_secrets import argon2_hashes, generate
    docs = generate(secrets.token_urlsafe(16), hasher=argon2_hashes)
    return {(d['metadata']['namespace'], d['metadata']['name']):
            {k: base64.b64decode(v).decode() for k, v in d['data'].items()} for d in docs}


def service_aliases(docs, namespace, labels):
    aliases = []
    for svc in docs:
        if svc['kind'] != 'Service' or svc['metadata'].get('namespace') != namespace:
            continue
        selector = svc['spec'].get('selector') or {}
        if selector and all(labels.get(k) == v for k, v in selector.items()):
            name = svc['metadata']['name']
            aliases += [name + '.' + namespace + '.svc.cluster.local', name + '.' + namespace + '.svc',
                        name + '.' + namespace]
    return aliases


def service_account_files(directory, namespace):
    """Projected service-account volume: a synthetic token, a self-signed CA (valid PEM) and the namespace."""
    from cryptography import x509
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import ec
    from cryptography.x509.oid import NameOID
    key = ec.generate_private_key(ec.SECP256R1())
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, 'smoke-cluster-ca')])
    now = datetime.datetime.now(datetime.timezone.utc)
    cert = (x509.CertificateBuilder().subject_name(name).issuer_name(name).public_key(key.public_key())
            .serial_number(x509.random_serial_number()).not_valid_before(now)
            .not_valid_after(now + datetime.timedelta(days=1))
            .add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True).sign(key, hashes.SHA256()))
    write(directory / 'token', 'smoke-' + secrets.token_hex(16))
    write(directory / 'ca.crt', cert.public_bytes(serialization.Encoding.PEM).decode())
    write(directory / 'namespace', namespace)


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    path.chmod(0o444)


def free_port():
    with socket.socket() as s:
        s.bind(('127.0.0.1', 0))
        return s.getsockname()[1]


class Workload:
    def __init__(self, doc, container, image, workdir, docs, secret_data):
        self.kind, self.namespace = doc['kind'], doc['metadata']['namespace']
        self.name = doc['metadata']['name']
        self.container = container
        self.image = image
        self.id = 'smoke-' + self.namespace + '-' + self.name + ('-' + container['name'] if container['name'] not in (
            self.name, 'agent', 'workload') else '')
        self.pod = doc['spec']['template']
        self.docs, self.secret_data, self.workdir = docs, secret_data, workdir / self.id
        self.ports = {}

    def config_map(self, name):
        found = [d for d in self.docs if d['kind'] == 'ConfigMap' and d['metadata']['name'] == name
                 and d['metadata'].get('namespace') == self.namespace]
        return found[0]['data'] if found else None

    def env(self):
        values = {}
        for item in self.container.get('env', []):
            if 'value' in item:
                values[item['name']] = item['value']
                continue
            source = item['valueFrom']
            if 'configMapKeyRef' in source:
                data = self.config_map(source['configMapKeyRef']['name'])
                values[item['name']] = data[source['configMapKeyRef']['key']]
            elif 'secretKeyRef' in source:
                ref = source['secretKeyRef']
                values[item['name']] = self.secret_data[(self.namespace, ref['name'])][ref['key']]
            else:
                raise ValueError('smoke:unsupported_env_source:' + self.id + ':' + item['name'])
        if self.container.get('envFrom'):
            raise ValueError('smoke:unsupported_envFrom:' + self.id)
        return values

    def security(self):
        pod, own = self.pod['spec'].get('securityContext', {}), self.container.get('securityContext', {})
        user = own.get('runAsUser', pod.get('runAsUser'))
        group = own.get('runAsGroup', pod.get('runAsGroup', user))
        options = []
        if user is not None:
            options += ['--user', f'{user}:{group}']
        if pod.get('fsGroup') is not None:
            options += ['--group-add', str(pod['fsGroup'])]
        if own.get('readOnlyRootFilesystem'):
            options.append('--read-only')
        if own.get('allowPrivilegeEscalation') is False:
            options += ['--security-opt', 'no-new-privileges']
        caps = own.get('capabilities', {})
        options += [x for c in caps.get('drop', []) for x in ('--cap-drop', c)]
        options += [x for c in caps.get('add', []) for x in ('--cap-add', c)]
        return options, user, pod.get('fsGroup', group)

    def volumes(self, user, group):
        declared = {v['name']: v for v in self.pod['spec'].get('volumes', [])}
        claims = {c['metadata']['name'] for c in self.doc_claims()}
        options = []
        for mount in self.container.get('volumeMounts', []):
            path, volume = mount['mountPath'], declared.get(mount['name'])
            ro = ':ro' if mount.get('readOnly') else ''
            if volume is None and mount['name'] in claims or volume is not None and 'persistentVolumeClaim' in volume:
                owner = f',uid={user},gid={group}' if user is not None else ''
                options += ['--tmpfs', path + ':rw,mode=0700,size=512m' + owner]
            elif volume is None:
                raise ValueError('smoke:undeclared_volume:' + self.id + ':' + mount['name'])
            elif 'emptyDir' in volume:
                options += ['--tmpfs', path + ':rw,mode=1777,size=256m']
            elif 'configMap' in volume or 'secret' in volume:
                local = self.workdir / mount['name']
                if 'configMap' in volume:
                    data = self.config_map(volume['configMap']['name'])
                    optional = volume['configMap'].get('optional', False)
                    items = volume['configMap'].get('items')
                else:
                    data = self.secret_data.get((self.namespace, volume['secret']['secretName']))
                    optional = volume['secret'].get('optional', False)
                    items = volume['secret'].get('items')
                if data is None:
                    if optional:
                        continue
                    raise ValueError('smoke:missing_volume_source:' + self.id + ':' + mount['name'])
                for key, value in data.items():
                    targets = [i['path'] for i in items if i['key'] == key] if items else [key]
                    for target in targets:
                        write(local / target, value)
                local.chmod(0o555)
                options += ['-v', f'{local}:{path}:ro']
            elif 'projected' in volume:
                local = self.workdir / mount['name']
                service_account_files(local, self.namespace)
                local.chmod(0o555)
                options += ['-v', f'{local}:{path}:ro']
            else:
                raise ValueError('smoke:unsupported_volume:' + self.id + ':' + mount['name'])
        return options

    def doc_claims(self):
        return []

    def probes(self):
        return [self.container[k] for k in ('startupProbe', 'readinessProbe') if k in self.container]

    def start(self, network):
        self.workdir.mkdir(parents=True, exist_ok=True)
        security, user, group = self.security()
        options = ['run', '-d', '--name', self.id, '--network', network, '--hostname', self.name]
        for alias in service_aliases(self.docs, self.namespace, self.pod['metadata'].get('labels', {})):
            options += ['--network-alias', alias]
        options += ['--restart', 'on-failure' if self.kind == 'Job' else 'always']
        limits = self.container.get('resources', {}).get('limits', {})
        if 'memory' in limits:
            options += ['--memory', limits['memory'].replace('Mi', 'm').replace('Gi', 'g')]
        for probe in self.probes():
            port = probe.get('httpGet', {}).get('port') or probe.get('tcpSocket', {}).get('port')
            if port and port not in self.ports:
                self.ports[port] = free_port()
                options += ['-p', f'127.0.0.1:{self.ports[port]}:{port}']
        for key, value in self.env().items():
            options += ['-e', key + '=' + value]
        options += security + self.volumes(user, group)
        command, args = self.container.get('command'), self.container.get('args')
        tail = []
        if command:
            options += ['--entrypoint', command[0]]
            tail = command[1:] + (args or [])
        elif args:
            tail = list(args)
        docker(*options, self.image, *tail)

    def inspect(self):
        state = json.loads(docker('inspect', self.id).stdout)[0]
        return state['State'], state['RestartCount'], state['NetworkSettings']['Networks']

    def probe_ok(self):
        for probe in self.probes():
            if 'httpGet' in probe:
                get = probe['httpGet']
                state, _, networks = self.inspect()
                address = next(iter(networks.values()))['IPAddress']
                request = urllib.request.Request(f"http://127.0.0.1:{self.ports[get['port']]}{get.get('path', '/')}",
                                                 headers={'Host': f"{address}:{get['port']}"})
                try:
                    with urllib.request.build_opener(urllib.request.ProxyHandler({})).open(
                            request, timeout=probe.get('timeoutSeconds', 1) + 1) as response:
                        if not 200 <= response.status < 400:
                            return False
                except (urllib.error.URLError, OSError, ValueError):
                    return False
            elif 'exec' in probe:
                result = docker('exec', self.id, *probe['exec']['command'], check=False)
                if result.returncode:
                    return False
            elif 'tcpSocket' in probe:
                try:
                    socket.create_connection(('127.0.0.1', self.ports[probe['tcpSocket']['port']]), 2).close()
                except OSError:
                    return False
        return True

    def logs(self, lines=60):
        result = docker('logs', '--tail', str(lines), self.id, check=False)
        return (result.stdout + result.stderr)[-6000:]


def workloads_for(docs, by_digest, images, workdir, secret_data):
    found = []
    for doc in docs:
        if doc['kind'] not in ('Deployment', 'StatefulSet', 'Job'):
            continue
        spec = doc['spec']['template']['spec']
        if spec.get('initContainers'):
            raise ValueError('smoke:init_containers_unsupported:' + doc['metadata']['name'])
        for container in spec['containers']:
            name = by_digest.get(container['image'].rsplit('@sha256:', 1)[-1])
            if name is None:
                raise ValueError('smoke:foreign_image:' + doc['metadata']['name'])
            workload = Workload(doc, container, images[name], workdir, docs, secret_data)
            if doc['kind'] == 'StatefulSet':
                templates = doc['spec'].get('volumeClaimTemplates', [])
                workload.doc_claims = lambda t=templates: t
            found.append(workload)
    return found


def entry_modules(workloads, images):
    """Python entry modules per image: every `-m` command and exec probe of its workloads, or the image ENTRYPOINT."""
    found = {}
    for w in workloads:
        name = next(n for n, r in images.items() if r == w.image)
        commands = [w.container.get('command')] + [p['exec']['command'] for p in w.probes() if 'exec' in p]
        if not w.container.get('command'):
            commands.append(json.loads(docker('image', 'inspect', '--format', '{{json .Config.Entrypoint}}',
                                              w.image).stdout or 'null'))
        for command in commands:
            if command and command[0].endswith('python3.12') and '-m' in command:
                found.setdefault(name, set()).add(command[command.index('-m') + 1])
        # Modules a mounted config loads by name (LiteLLM `callbacks: package.module.attribute`).
        for mount in w.container.get('volumeMounts', []):
            volume = next((v for v in w.pod['spec'].get('volumes', []) if v['name'] == mount['name']), {})
            for text in (w.config_map(volume['configMap']['name']) or {}).values() if 'configMap' in volume else ():
                for line in text.splitlines():
                    key, _, value = line.strip().partition(':')
                    if key == 'callbacks' and value.strip().startswith('agent_platform.'):
                        found.setdefault(name, set()).add(value.strip().rsplit('.', 1)[0])
    return found


def import_sweep(workloads, images):
    """Supplementary: no reachable import may be missing from an image (scripts/image-import-sweep.py, run inside)."""
    report = {}
    for name, modules in sorted(entry_modules(workloads, images).items()):
        result = docker('run', '--rm', '--network', 'none', '--read-only', '--entrypoint', '/usr/local/bin/python3.12',
                        '-v', f"{ROOT / 'scripts/image-import-sweep.py'}:/sweep/image-import-sweep.py:ro",
                        images[name], '-B', '/sweep/image-import-sweep.py', *sorted(modules), check=False)
        try:
            parsed = json.loads(result.stdout)
        except ValueError:
            parsed = {'missing': [{'module': '<sweep failed>', 'imported_by': result.stderr[-500:], 'line': 0}]}
        report[name] = {'entries': sorted(modules), 'missing': parsed.get('missing', []),
                        'optional_missing': parsed.get('optional_missing', [])}
    return report


def run(images, kubectl, out):
    docs, by_digest = render_workloads(kubectl)
    if set(images) != set(LOCK_KEYS.values()):
        raise ValueError('smoke:seven_images_required')
    secret_data = synthetic_secrets()
    workdir = Path(tempfile.mkdtemp(prefix='runtime-smoke-'))
    network = 'smoke-' + secrets.token_hex(4)
    workloads = workloads_for(docs, by_digest, images, workdir, secret_data)
    results = {w.id: {'kind': w.kind, 'image': next(n for n, r in images.items() if r == w.image)} for w in workloads}
    sweep = import_sweep(workloads, images)
    docker('network', 'create', network)
    try:
        for w in workloads:
            w.start(network)
        deadline = time.time() + READY_SECONDS
        pending = {w.id for w in workloads}
        while pending and time.time() < deadline:
            for w in workloads:
                if w.id not in pending:
                    continue
                state, restarts, _ = w.inspect()
                if w.kind == 'Job':
                    if state['Status'] == 'exited' and state['ExitCode'] == 0:
                        results[w.id].update(status='completed', restarts=restarts)
                        pending.discard(w.id)
                elif state['Status'] == 'running' and w.probe_ok():
                    results[w.id].update(status='ready', restarts_before_ready=restarts)
                    pending.discard(w.id)
            if pending:
                time.sleep(PERIOD)
        for w in workloads:
            if w.id in pending:
                state, restarts, _ = w.inspect()
                results[w.id].update(status='not_ready', state=state['Status'], exit_code=state.get('ExitCode'),
                                     restarts=restarts, logs=w.logs())
        ready = [w for w in workloads if results[w.id]['status'] == 'ready']
        baseline = {w.id: w.inspect()[1] for w in ready}
        end = time.time() + STABLE_SECONDS
        while time.time() < end:
            for w in ready:
                if results[w.id]['status'] != 'ready':
                    continue
                state, restarts, _ = w.inspect()
                if state['Status'] != 'running' or restarts != baseline[w.id] or not w.probe_ok():
                    results[w.id].update(status='unstable', state=state['Status'], restarts=restarts, logs=w.logs())
            time.sleep(PERIOD)
        for w in ready:
            if results[w.id]['status'] == 'ready':
                results[w.id]['status'] = 'stable'
    finally:
        for w in workloads:
            docker('rm', '-f', w.id, check=False)
        docker('network', 'rm', network, check=False)
        shutil.rmtree(workdir, ignore_errors=True)
    passed = (all(r['status'] in ('stable', 'completed') for r in results.values())
              and not any(s['missing'] for s in sweep.values()))
    report = {'passed': passed, 'stability_seconds': STABLE_SECONDS, 'workloads': results, 'import_sweep': sweep}
    Path(out).write_text(json.dumps(report, indent=1, sort_keys=True) + '\n')
    for name, result in sorted(sweep.items()):
        print(f"import sweep {name}: {len(result['missing'])} missing" + ''.join(
            f"\n  {m['module']} <- {m['imported_by']}:{m['line']}" for m in result['missing']))
    for name, result in sorted(results.items()):
        print(f"{result['status']:<10} {name:<52} {result['image']}")
        if result['status'] not in ('stable', 'completed'):
            print('  last log lines:\n    ' + '\n    '.join(result.get('logs', '').splitlines()[-25:]))
    return passed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--images', type=Path, required=True,
                        help='JSON {image name: local image reference} for all seven release images')
    parser.add_argument('--kubectl', required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    images = json.loads(args.images.read_text())
    if not run(images, args.kubectl, args.out):
        raise SystemExit('runtime smoke failed: every declared workload must run (see report)')
    print('runtime smoke passed: every declared workload ran with its exact command')


if __name__ == '__main__':
    main()
