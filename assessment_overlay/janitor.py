"""Independent fail-closed billing unlink and disposable-project deletion.

The janitor uses the private run manifest generated by live_session. It never
accepts an arbitrary project name and never reports a clean termination unless
billing is unlinked and deletion is confirmed. An operator can invoke the same
cleanup after completing the cases; the independent runner is the fallback.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import subprocess
import time

from live_case_guard import PROJECT_PATTERN, RUN_PATTERN

JANITOR_PROVIDER_SUFFIX = '/locations/global/workloadIdentityPools/assessment-janitor/providers/assessment-janitor'


def load_manifest(path):
    manifest = json.loads(Path(path).read_text())
    project = manifest.get('disposable_project_id', '')
    run_id = manifest.get('run_id', '')
    if manifest.get('schema_version') != 1 or not PROJECT_PATTERN.fullmatch(project) \
            or not RUN_PATTERN.fullmatch(run_id) or manifest.get('cleanup_required') != [
                'resource_absence', 'billing_unlinked', 'project_delete_requested']:
        raise ValueError('invalid disposable assessment manifest')
    deadline = datetime.fromisoformat(manifest['deadline_at'])
    if deadline.tzinfo is None:
        raise ValueError('assessment deadline must be timezone-aware')
    return manifest


def gcloud_json(*args):
    result = subprocess.run(['gcloud', *args, '--format=json'], capture_output=True, text=True, timeout=60)
    if result.returncode:
        raise RuntimeError('janitor:gcloud_failed:' + args[0] + ':' + args[1])
    return json.loads(result.stdout or 'null')


def inspect_project(project, run_id, call=gcloud_json):
    described = call('projects', 'describe', project)
    if described.get('projectId') != project or described.get('labels', {}).get('assessment_run') != run_id:
        raise RuntimeError('janitor:project_identity_mismatch')
    return described


def validate_janitor_identity(project, run_id, provider, service_account, call=gcloud_json):
    """Refuse an identity outside the project this workflow is allowed to delete."""
    if not PROJECT_PATTERN.fullmatch(project or '') or not RUN_PATTERN.fullmatch(run_id or ''):
        raise ValueError('janitor:invalid_disposable_identity')
    described = inspect_project(project, run_id, call)
    number = str(described.get('projectNumber', ''))
    expected_provider = 'projects/' + number + JANITOR_PROVIDER_SUFFIX
    expected_sa = 'assessment-janitor@' + project + '.iam.gserviceaccount.com'
    if not number.isdigit() or provider != expected_provider or service_account != expected_sa:
        raise ValueError('janitor:identity_mismatch')
    return described


def resource_absence(project, call=gcloud_json):
    """Check the billable and deployable resource classes before project deletion."""
    inventories = {
        'clusters': ('container', 'clusters', 'list'),
        'instances': ('compute', 'instances', 'list'),
        'disks': ('compute', 'disks', 'list'),
        'snapshots': ('compute', 'snapshots', 'list'),
        'addresses': ('compute', 'addresses', 'list'),
        'forwarding_rules': ('compute', 'forwarding-rules', 'list'),
        'routers': ('compute', 'routers', 'list'),
        'networks': ('compute', 'networks', 'list'),
        'subnetworks': ('compute', 'networks', 'subnets', 'list'),
        'routes': ('compute', 'routes', 'list'),
        'firewall_rules': ('compute', 'firewall-rules', 'list'),
        'buckets': ('storage', 'buckets', 'list'),
        'repositories': ('artifacts', 'repositories', 'list', '--location=us-east1'),
    }
    counts = {}
    for name, command in inventories.items():
        items = call(*command, '--project=' + project)
        if not isinstance(items, list):
            raise RuntimeError('janitor:inventory_unreadable:' + name)
        counts[name] = len(items)
    return counts


def cleanup(manifest, *, call=gcloud_json, now=None):
    project, run_id = manifest['disposable_project_id'], manifest['run_id']
    described = inspect_project(project, run_id, call)
    if described.get('lifecycleState') not in ('ACTIVE', 'DELETE_REQUESTED'):
        raise RuntimeError('janitor:project_state_unexpected')
    counts = {}
    try:
        if described['lifecycleState'] == 'ACTIVE':
            counts = resource_absence(project, call)
    except RuntimeError:
        pass  # An unreadable inventory must not prevent billing unlink/deletion.
    billing_unlinked = False
    try:
        billing = call('billing', 'projects', 'describe', project)
        if billing.get('billingEnabled') is not False or billing.get('billingAccountName'):
            call('billing', 'projects', 'unlink', project, '--quiet')
            billing = call('billing', 'projects', 'describe', project)
        billing_unlinked = billing.get('billingEnabled') is False and not billing.get('billingAccountName')
    except RuntimeError:
        # Continue to project deletion, which is safer than leaving a paid run.
        pass
    deletion_requested = False
    try:
        if described['lifecycleState'] == 'ACTIVE':
            call('projects', 'delete', project, '--quiet')
        final = inspect_project(project, run_id, call)
        deletion_requested = final.get('lifecycleState') == 'DELETE_REQUESTED'
    except RuntimeError:
        pass
    now = now or datetime.now(timezone.utc)
    return {
        'run_id': run_id,
        'project_sha256': hashlib.sha256(project.encode()).hexdigest(),
        'verified_at': now.isoformat(),
        'resource_counts_before_delete': counts,
        'resource_absence': bool(counts) and all(count == 0 for count in counts.values()),
        'billing_unlinked': billing_unlinked,
        'project_delete_requested': deletion_requested,
        'result': ('PASS' if counts and all(count == 0 for count in counts.values()) and billing_unlinked
                   and deletion_requested else 'TAKEOVER' if deletion_requested else 'FAIL'),
    }


def write_receipt(path, receipt):
    with os.fdopen(os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), 'w') as stream:
        json.dump(receipt, stream, indent=2, sort_keys=True)
        stream.write('\n')


def wait_until_deadline(manifest, *, now=lambda: datetime.now(timezone.utc), sleep=time.sleep):
    deadline = datetime.fromisoformat(manifest['deadline_at'])
    if deadline.tzinfo is None:
        raise ValueError('assessment deadline must be timezone-aware')
    while True:
        remaining = (deadline - now()).total_seconds()
        if remaining <= 0:
            return
        print(json.dumps({'run_id': manifest['run_id'], 'janitor': 'armed',
                          'seconds_to_deadline': int(remaining)}), flush=True)
        sleep(min(60, remaining))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--run-dir', type=Path)
    parser.add_argument('--project-id')
    parser.add_argument('--run-id')
    parser.add_argument('--deadline-at')
    parser.add_argument('--workload-identity-provider')
    parser.add_argument('--service-account')
    parser.add_argument('--execute', action='store_true')
    parser.add_argument('--watch', action='store_true', help='remain independent until the hard deadline')
    args = parser.parse_args()
    if args.run_dir:
        manifest = load_manifest(args.run_dir / 'initial-manifest.json')
        output = args.run_dir / 'evidence/janitor-cleanup.json'
    else:
        manifest = {'schema_version': 1, 'disposable_project_id': args.project_id,
                    'run_id': args.run_id, 'deadline_at': args.deadline_at,
                    'cleanup_required': ['resource_absence', 'billing_unlinked', 'project_delete_requested']}
        if not PROJECT_PATTERN.fullmatch(args.project_id or '') or not RUN_PATTERN.fullmatch(args.run_id or ''):
            raise SystemExit('janitor:invalid_disposable_identity')
        deadline = datetime.fromisoformat(args.deadline_at)
        if deadline.tzinfo is None:
            raise SystemExit('janitor:deadline_timezone_required')
        validate_janitor_identity(args.project_id, args.run_id,
                                  args.workload_identity_provider, args.service_account)
        output = Path(os.environ.get('RUNNER_TEMP', '/tmp')) / ('janitor-' + args.run_id + '.json')
    if not args.execute:
        raise SystemExit('janitor:explicit_execute_required')
    if args.watch:
        wait_until_deadline(manifest)
    receipt = cleanup(manifest)
    write_receipt(output, receipt)
    print(json.dumps({'run_id': receipt['run_id'], 'result': receipt['result'],
                      'resource_absence': receipt['resource_absence'],
                      'billing_unlinked': receipt['billing_unlinked'],
                      'project_delete_requested': receipt['project_delete_requested']}))
    if receipt['result'] != 'PASS':
        raise SystemExit(2)


if __name__ == '__main__':
    main()
