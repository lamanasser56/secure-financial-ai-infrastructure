"""Registered targets, read from the same ConfigMap that parameterises the admission policy.

Mutable targets have "<namespace>.<deployment>.min|max|health". Read-only core targets have only
"<namespace>.<deployment>.observe" = "read-only". Mixed declarations are refused. Observation never
grants proposal or execution authority; the executor and admission policy enforce that separation.
"""
from dataclasses import dataclass
from pathlib import Path
import re

ACTIONS = ('restart', 'scale')  # no rollback: the agent never changes a Pod spec
NAME = re.compile(r'[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?')


@dataclass(frozen=True)
class Target:
    namespace: str
    name: str
    min_replicas: int
    max_replicas: int
    health: str | None
    observe_only: bool = False  # health observation only, never a proposal or a change

    @property
    def key(self):
        return self.namespace + '.' + self.name


def parse(data):
    groups = {}
    for key, value in data.items():
        parts = key.split('.')
        if len(parts) != 3 or parts[2] not in ('min', 'max', 'health', 'observe'):
            raise ValueError('registry:key ' + key)
        groups.setdefault((parts[0], parts[1]), {})[parts[2]] = value
    targets = {}
    for (namespace, name), fields in sorted(groups.items()):
        if not NAME.fullmatch(namespace) or not NAME.fullmatch(name):
            raise ValueError('registry:incomplete ' + namespace + '.' + name)
        if set(fields) == {'observe'}:
            if fields['observe'] != 'read-only':
                raise ValueError('registry:observe ' + namespace + '.' + name)
            targets[namespace + '.' + name] = Target(namespace, name, 0, 0, None, observe_only=True)
            continue
        if set(fields) != {'min', 'max', 'health'}:
            raise ValueError('registry:incomplete ' + namespace + '.' + name)
        low, high = int(fields['min']), int(fields['max'])
        if not 0 <= low <= high <= 5:
            raise ValueError('registry:bounds ' + namespace + '.' + name)
        health = None if fields['health'] == 'none' else fields['health']
        if health is not None and not re.fullmatch(r'http://[a-z0-9.-]+\.svc\.cluster\.local:\d+/[\w/.-]*', health):
            raise ValueError('registry:health ' + namespace + '.' + name)
        targets[namespace + '.' + name] = Target(namespace, name, low, high, health)
    return targets


def load(directory=Path('/registry')):
    return parse({p.name: p.read_text() for p in Path(directory).iterdir() if not p.name.startswith('.')})


def parse_observe(data):
    """Keys "<namespace>.<deployment>.observe" = "read-only" (generated by `make onboard` for onboarded agents)."""
    targets = {}
    for key, value in data.items():
        parts = key.split('.')
        if (len(parts) != 3 or parts[2] != 'observe' or value != 'read-only' or not parts[0].startswith('agent-')
                or not NAME.fullmatch(parts[0]) or not NAME.fullmatch(parts[1])):
            raise ValueError('registry:observe ' + key)
        targets[parts[0] + '.' + parts[1]] = Target(parts[0], parts[1], 0, 0, None, observe_only=True)
    return targets


def load_observe(directory=Path('/observe')):
    directory = Path(directory)
    if not directory.is_dir():
        return {}
    return parse_observe({p.name: p.read_text() for p in directory.iterdir() if not p.name.startswith('.')})
