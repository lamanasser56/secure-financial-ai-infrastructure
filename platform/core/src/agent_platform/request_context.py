"""One request ID per user request, carried from the entry point to the redactor and the gateway.

The ID is 32 lowercase hex characters (uuid4). It is generated by the service that receives the user's request, bound to
the current context, and sent as the `X-Request-ID` header (and as LiteLLM request metadata) so that the redactor's and
the gateway's audit lines carry the same value. It carries no user data. A value received from a peer is accepted only
in this exact shape; anything else is dropped, never logged.
"""
import contextlib
import contextvars
import re
import uuid

HEADER = 'X-Request-ID'
_PATTERN = re.compile(r'[0-9a-f]{32}')
_CURRENT = contextvars.ContextVar('request_id', default=None)


def new():
    return uuid.uuid4().hex


def accept(value):
    """The value if it has the exact request-ID shape, else None."""
    return value if isinstance(value, str) and _PATTERN.fullmatch(value) else None


def current():
    return _CURRENT.get()


@contextlib.contextmanager
def bind(request_id):
    token = _CURRENT.set(accept(request_id))
    try:
        yield request_id
    finally:
        _CURRENT.reset(token)
